#!/usr/bin/env bash
# benchmark.sh - compare the C++ logparser with the Python devtool on a generated log.
# Usage: benchmark.sh [LINES] [RUNS]   (run `make cpp-build` and activate .venv first)
set -euo pipefail
trap 'echo "ERROR: failed at line $LINENO" >&2' ERR

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)

LINES=${1:-1000000}
RUNS=${2:-5}
LOG=${TMPDIR:-/tmp}/toolkit-bench.log
OUT="$ROOT/docs/benchmarks.md"
TABLE=$(mktemp)

command -v hyperfine >/dev/null || die 'hyperfine not found: sudo apt install hyperfine'
command -v devtool >/dev/null || die 'devtool not found: activate .venv'
[[ -x $ROOT/build/logparser ]] || die 'logparser not built: run make cpp-build'

"$SCRIPT_DIR/gen-log.sh" "$LINES" > "$LOG"
log "generated $LINES lines ($(du -h "$LOG" | cut -f1))"

diff <("$ROOT/build/logparser" "$LOG") <(devtool logs "$LOG") >/dev/null || die 'outputs differ'
log 'outputs are identical'

hyperfine -N --warmup 1 --runs "$RUNS" --export-markdown "$TABLE" \
  -n 'C++ logparser' "$ROOT/build/logparser $LOG" \
  -n 'Python devtool' "devtool logs $LOG"

{
  echo '# Benchmarks'
  echo
  echo "Input: $LINES generated nginx access-log lines ($(du -h "$LOG" | cut -f1))."
  echo "Machine: $(lscpu | awk -F: '/Model name/ {gsub(/^ +/, "", $2); print $2}'), $(nproc) threads, $(free -g | awk '/Mem:/ {print $2}') GB RAM."
  echo "Method: hyperfine, 1 warm-up and $RUNS timed runs. Generated by scripts/benchmark.sh."
  echo "Both tools produce byte-identical output (checked before timing)."
  echo
  cat "$TABLE"
} > "$OUT"
rm -f "$TABLE" "$LOG"
log "written $OUT"
